using Twip;

namespace Examples;

static class SessionExample
{
    static async Task Run()
    {
        #region session
        // An unattached session is headless: a console app, a service, a test.
        await using var session = new EditorSession(new EditorSessionOptions(Author: new Author("Report bot")));

        var opened = await session.OpenAsync("template.docx");
        foreach (var warning in opened.Warnings) Console.WriteLine($"{warning.Code}: {warning.Message}");

        // One method per command. Each completes after its change commits, with State at that revision.
        await session.Commands.MoveSelectionAsync(MoveUnit.Document, Direction.Forward);
        await session.Commands.InsertTextAsync("Generated by Twip.");
        await session.Commands.SelectAllAsync();
        await session.Commands.SetBoldAsync(true);
        Console.WriteLine(session.State.Formatting.Bold.IsOn); // True

        // A batch is atomic: one transaction and one undo step, or nothing when an operation fails.
        await session.BatchAsync([EditorOperation.SetBold(false), EditorOperation.SetAlignment(ParagraphAlignment.Center)], "Center");

        await session.SaveAsync("report.docx");
        await session.ExportPdfAsync("report.pdf");
        #endregion
    }

    static async Task Errors(EditorSession session, Stream upload)
    {
        #region errors
        try
        {
            await session.OpenAsync(upload);
        }
        catch (EditorException e) when (e.Code == EditorErrorCode.ImportFailed)
        {
            Console.WriteLine("Not a document Twip can read. The session keeps its current document.");
        }
        #endregion
    }
}
