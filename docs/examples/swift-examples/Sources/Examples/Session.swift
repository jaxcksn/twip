import Foundation
import Twip

enum SessionExample {
    static func run() async throws {
        // #region session
        // A session with no view is headless: a command-line tool, a service, a test.
        let session = EditorSession(options: SessionOptions(author: Author(name: "Report bot")))

        let warnings = try await session.open(contentsOf: URL(filePath: "template.docx"))
        for warning in warnings { print("\(warning.code): \(warning.message)") }

        // Commands are values. Each run completes after its change commits, with `state` at that revision.
        try await session.run(.moveSelection(by: .document, direction: .forward))
        try await session.run(.insertText("Generated by Twip."))
        try await session.run(.selectAll)
        try await session.run(.setBold(true))
        print(session.state.formatting.bold.isOn) // true

        // A batch is atomic: one transaction and one undo step, or nothing when a command fails.
        try await session.batch([.setBold(false), .setAlignment(.center)], label: "Center")

        try await session.save(to: URL(filePath: "report.docx"))
        try await session.exportPDF(to: URL(filePath: "report.pdf"))
        await session.close()
        // #endregion
    }

    static func errors(_ session: EditorSession, upload: Data) async {
        // #region errors
        do {
            try await session.open(upload)
        } catch let error as TwipError where error.code == .importFailed {
            print("Not a document Twip can read. The session keeps its current document.")
        } catch {
            print("Couldn't open it: \(error)")
        }
        // #endregion
    }
}
