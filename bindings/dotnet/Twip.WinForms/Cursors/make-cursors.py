"""Writes the editor's table and margin selection cursors and its rotate cursor as Windows .cur files, next to this script for the
WinForms host and, inlined as data URLs, for the browser host (bindings/web/src/host/cursors.ts). Standard library
only, no randomness: the same bytes on every run.

Run: python -I bindings/dotnet/Twip.WinForms/Cursors/make-cursors.py
"""

import base64
import math
import struct
from pathlib import Path

SIZE = 32
SAMPLES = 4  # per pixel side, for anti-aliased edges
OUTLINE = 0.6  # px each side of an edge

BLACK, WHITE = (0, 0, 0), (255, 255, 255)


def rotate_arrow(c=16.0, r_in=6.5, r_out=9.5, start=-45.0, sweep=270.0, steps=24):
    """A 3 px band on a circle from `start` round `sweep` degrees clockwise, ending in an arrowhead."""
    at = lambda r, deg: (c + r * math.cos(math.radians(deg)), c + r * math.sin(math.radians(deg)))
    end = start + sweep
    arc = [start + sweep * k / steps for k in range(steps + 1)]
    mid, e = (r_in + r_out) / 2, math.radians(end)
    tip = (c + mid * math.cos(e) - 5 * math.sin(e), c + mid * math.sin(e) + 5 * math.cos(e))
    head = [at(r_out + 2.5, end), tip, at(r_in - 2.5, end)]
    return [at(r_out, a) for a in arc] + head + [at(r_in, a) for a in reversed(arc)]


# name: (polygon in pixels, fill, outline, hotspot)
CURSORS = {
    # A cell's selection zone: a black arrow pointing up and right.
    "cell-select": ([(29, 3), (29, 12), (26, 9), (20, 15), (17, 12), (23, 6), (20, 3)], BLACK, WHITE, (29, 3)),
    # A column's selection zone: a black arrow pointing down.
    "column-select": ([(14, 3), (18, 3), (18, 9), (21, 9), (16, 14), (11, 9), (14, 9)], BLACK, WHITE, (16, 14)),
    # A row's selection zone and the margin: the white arrow, mirrored to point up and right.
    "row-select": ([(29, 3), (29, 20), (25, 16), (22, 22), (20, 21), (23, 15), (17, 15)], WHITE, BLACK, (29, 3)),
    # A shape's rotate handle: a black circular arrow, its hotspot the circle's centre.
    "rotate": (rotate_arrow(), BLACK, WHITE, (16, 16)),
}


def inside(poly, x, y):
    """Even-odd point in polygon."""
    hit = False
    for (x0, y0), (x1, y1) in zip(poly, poly[1:] + poly[:1]):
        if (y0 > y) != (y1 > y) and x < x0 + (y - y0) * (x1 - x0) / (y1 - y0):
            hit = not hit
    return hit


def edge_distance(poly, x, y):
    best = float("inf")
    for (x0, y0), (x1, y1) in zip(poly, poly[1:] + poly[:1]):
        dx, dy = x1 - x0, y1 - y0
        t = max(0.0, min(1.0, ((x - x0) * dx + (y - y0) * dy) / (dx * dx + dy * dy)))
        best = min(best, ((x - x0 - t * dx) ** 2 + (y - y0 - t * dy) ** 2) ** 0.5)
    return best


def pixels(poly, fill, outline):
    """Rows top to bottom of (r, g, b, a): the outline over the fill, coverage from SAMPLES² samples a pixel."""
    out = []
    for py in range(SIZE):
        row = []
        for px in range(SIZE):
            f = o = 0
            for sy in range(SAMPLES):
                for sx in range(SAMPLES):
                    x, y = px + (sx + 0.5) / SAMPLES, py + (sy + 0.5) / SAMPLES
                    if edge_distance(poly, x, y) <= OUTLINE:
                        o += 1
                    elif inside(poly, x, y):
                        f += 1
            n = SAMPLES * SAMPLES
            a = (f + o) / n
            rgb = tuple(round((c1 * f + c2 * o) / (f + o)) if f + o else 0 for c1, c2 in zip(fill, outline))
            row.append((*rgb, round(a * 255)))
        out.append(row)
    return out


def cur(rows, hotspot):
    """A one-image .cur: 32-bit BGRA with alpha, an all-clear AND mask."""
    xor = b"".join(bytes((b, g, r, a)) for row in reversed(rows) for (r, g, b, a) in row)
    mask = bytes(SIZE * SIZE // 8)
    header = struct.pack("<IiiHHIIiiII", 40, SIZE, SIZE * 2, 1, 32, 0, len(xor) + len(mask), 0, 0, 0, 0)
    image = header + xor + mask
    directory = struct.pack("<HHH", 0, 2, 1) + struct.pack("<BBBBHHII", SIZE, SIZE, 0, 0, *hotspot, len(image), 22)
    return directory + image


def main():
    winforms = Path(__file__).resolve().parent
    root = winforms.parents[2]
    ts = [
        "// Generated by bindings/dotnet/Twip.WinForms/Cursors/make-cursors.py: do not edit.",
        "// The table and margin selection cursors and the rotate cursor as .cur data URLs, with their hotspots.",
        "",
    ]
    for name, (poly, fill, outline, hotspot) in CURSORS.items():
        data = cur(pixels(poly, fill, outline), hotspot)
        (winforms / f"{name}.cur").write_bytes(data)
        const = name.upper().replace("-", "_")
        ts.append(f"export const {const} = {{ url: 'data:image/x-icon;base64,{base64.b64encode(data).decode()}', x: {hotspot[0]}, y: {hotspot[1]} }};")
    (root / "web" / "src" / "host" / "cursors.ts").write_text("\n".join(ts) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(CURSORS)} cursors to {winforms} and bindings/web/src/host/cursors.ts")


if __name__ == "__main__":
    main()
