"""Writes codepages.rs: the upper half of the Windows single-byte code pages, from Python's own codecs.

A byte the page leaves undefined keeps its value (a C1 control), as GDI shows it. Standard library only.
Run: python3 crates/twip-tools/scripts/gen-codepages.py > crates/twip/src/render/metafile/codepages.rs
The output is what rustfmt (max_width 150) makes of it: seventeen entries to a line.
"""

PAGES = [1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258, 874]


def row(page):
    out = []
    for b in range(0x80, 0x100):
        try:
            out.append(ord(bytes([b]).decode(f"cp{page}")))
        except UnicodeDecodeError:
            out.append(b)
    return out


print("//! Windows single-byte code pages: the characters of bytes 0x80 to 0xFF. Generated by gen-codepages.py.")
print()
print("/// The code pages, in the order of the tables: 1250 to 1258 and 874.")
print(f"pub(super) static TABLES: [[u16; 128]; {len(PAGES)}] = [")
for page in PAGES:
    print(f"    // {page}")
    print("    [")
    r = row(page)
    for i in range(0, 128, 17):
        print("        " + ", ".join(f"0x{v:04X}" for v in r[i:i + 17]) + ",")
    print("    ],")
print("];")
