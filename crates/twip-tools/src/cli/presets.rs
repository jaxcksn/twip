//! `twip presets <presetShapeDefinitions.xml> <out.rs>`: the engine's preset geometry table
//! (`crates/twip/src/drawing/geom/presets.rs`) generated from the standard's definitions (ECMA-376 Part 1, the
//! `OfficeOpenXML-DrawingMLGeometries.zip` insert). Each preset is compiled as a custom geometry is
//! (`CustomGeom::parse`) and written as a static `GeomDef`.

use std::fmt::Write;
use std::path::Path;

use twip::internal::drawing::geom::CustomGeom;

/// `rect` → `Rect`, `flowChartAlternateProcess` → `FlowChartAlternateProcess`.
fn variant(name: &str) -> String {
    let mut c = name.chars();
    c.next().map(|f| f.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
}

/// `upArrow`: the standard's `downArrow` turned top to bottom (its guides, handles, connection sites, text rectangle
/// and path mirrored).
const UP_ARROW: &str = r#"<upArrow xmlns="http://schemas.openxmlformats.org/drawingml/2006/main">
  <avLst><gd name="adj1" fmla="val 50000"/><gd name="adj2" fmla="val 50000"/></avLst>
  <gdLst>
    <gd name="maxAdj2" fmla="*/ 100000 h ss"/>
    <gd name="a1" fmla="pin 0 adj1 100000"/>
    <gd name="a2" fmla="pin 0 adj2 maxAdj2"/>
    <gd name="dy1" fmla="*/ ss a2 100000"/>
    <gd name="y1" fmla="+- t dy1 0"/>
    <gd name="dx1" fmla="*/ w a1 200000"/>
    <gd name="x1" fmla="+- hc 0 dx1"/>
    <gd name="x2" fmla="+- hc dx1 0"/>
    <gd name="dy2" fmla="*/ x1 dy1 wd2"/>
    <gd name="y2" fmla="+- y1 0 dy2"/>
  </gdLst>
  <ahLst>
    <ahXY gdRefX="adj1" minX="0" maxX="100000"><pos x="x1" y="b"/></ahXY>
    <ahXY gdRefY="adj2" minY="0" maxY="maxAdj2"><pos x="l" y="y1"/></ahXY>
  </ahLst>
  <cxnLst>
    <cxn ang="3cd4"><pos x="hc" y="t"/></cxn>
    <cxn ang="cd2"><pos x="l" y="y1"/></cxn>
    <cxn ang="cd4"><pos x="hc" y="b"/></cxn>
    <cxn ang="0"><pos x="r" y="y1"/></cxn>
  </cxnLst>
  <rect l="x1" t="y2" r="x2" b="b"/>
  <pathLst>
    <path>
      <moveTo><pt x="l" y="y1"/></moveTo>
      <lnTo><pt x="hc" y="t"/></lnTo>
      <lnTo><pt x="r" y="y1"/></lnTo>
      <lnTo><pt x="x2" y="y1"/></lnTo>
      <lnTo><pt x="x2" y="b"/></lnTo>
      <lnTo><pt x="x1" y="b"/></lnTo>
      <lnTo><pt x="x1" y="y1"/></lnTo>
      <close/>
    </path>
  </pathLst>
</upArrow>"#;

/// Writes the table to `out`. Returns an error message if the definitions can't be read or the file written.
pub fn run(xml: &Path, out: &Path) -> Result<(), String> {
    let text = std::fs::read_to_string(xml).map_err(|e| format!("{}: {e}", xml.display()))?;
    let doc = roxmltree::Document::parse(text.trim_start_matches('\u{feff}')).map_err(|e| format!("{}: {e}", xml.display()))?;
    let mut presets: Vec<(String, Vec<u8>)> = doc
        .root_element()
        .children()
        .filter(|c| c.is_element())
        .map(|el| {
            let name = el.tag_name().name().to_string();
            let def = CustomGeom::parse(el).to_bytes();
            (name, def)
        })
        .collect();
    // The standard's file defines `upDownArrow` twice, alike, and `upArrow` not at all (the second `upDownArrow` stands
    // where it would): keep one `upDownArrow`, and make `upArrow` as `downArrow` mirrored top to bottom.
    if !presets.iter().any(|p| p.0 == "upArrow") {
        let up = roxmltree::Document::parse(UP_ARROW).map_err(|e| format!("upArrow: {e}"))?;
        presets.push(("upArrow".into(), CustomGeom::parse(up.root_element()).to_bytes()));
    }
    presets.sort();
    presets.dedup_by(|a, b| a.0 == b.0);
    let mut s = String::new();
    s.push_str(
        "//! GENERATED by `twip-tools presets` from the preset shape definitions of ECMA-376 Part 1 (5th edition,\n\
         //! `presetShapeDefinitions.xml`; see licenses/ecma-376.txt; `upArrow`, missing there, is its `downArrow`\n\
         //! mirrored). Do not edit: regenerate.\n\n\
         use super::GeomDef;\n\n",
    );
    s.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum Preset {\n");
    for (n, _) in &presets {
        let _ = writeln!(s, "    {},", variant(n));
    }
    s.push_str("}\n\nimpl Preset {\n    pub const ALL: &'static [Preset] = &[\n");
    for (n, _) in &presets {
        let _ = writeln!(s, "        Preset::{},", variant(n));
    }
    s.push_str("    ];\n\n    pub fn name(self) -> &'static str {\n        match self {\n");
    for (n, _) in &presets {
        let _ = writeln!(s, "            Preset::{} => {n:?},", variant(n));
    }
    s.push_str("        }\n    }\n\n    pub fn from_name(s: &str) -> Option<Preset> {\n        Some(match s {\n");
    for (n, _) in &presets {
        let _ = writeln!(s, "            {n:?} => Preset::{},", variant(n));
    }
    let _ = write!(
        s,
        "            _ => return None,\n        }})\n    }}\n\n    pub(super) fn def(self) -> GeomDef<'static> {{\n        \
         static DEFS: [std::sync::OnceLock<GeomDef<'static>>; {n}] = [const {{ std::sync::OnceLock::new() }}; {n}];\n        \
         *DEFS[self as usize].get_or_init(|| super::pack::decode(PACKED[self as usize]))\n    }}\n}}\n\n\
         #[rustfmt::skip]\nstatic PACKED: [&[u8]; {n}] = [\n",
        n = presets.len()
    );
    for (_, d) in &presets {
        s.push_str("    b\"");
        for &b in d {
            if (0x20..0x7f).contains(&b) && b != b'\\' && b != b'"' {
                s.push(b as char);
            } else {
                let _ = write!(s, "\\x{b:02x}");
            }
        }
        s.push_str("\",\n");
    }
    s.push_str("];\n");
    std::fs::write(out, s).map_err(|e| format!("{}: {e}", out.display()))?;
    println!("wrote {} presets to {}", presets.len(), out.display());
    Ok(())
}
