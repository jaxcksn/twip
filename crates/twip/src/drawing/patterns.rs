#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_preset_has_a_tile_and_the_percentages_cover_their_share() {
        for &p in PatternPreset::ALL {
            let _ = tile(p);
        }
        let ink = |p: PatternPreset| tile(p).iter().map(|r| r.count_ones()).sum::<u32>();
        assert_eq!(ink(PatternPreset::Pct50), 32);
        assert_eq!(ink(PatternPreset::Pct25), 16);
        assert_eq!(ink(PatternPreset::Horz), 8);
    }
}
